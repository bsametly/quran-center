-- 6) تحديث سياسات الأمان (Row Level Security - RLS)
-- السماح لتطبيق المركز بعمليات القراءة والكتابة بالـ Anon / Publishable Key
-- لحل مشكلة "new row violates row-level security policy" تماماً
do $$
declare
  t text;
  tables text[] := array[
    'profiles', 'teachers', 'parents', 'halaqat', 'students',
    'recitations', 'mistakes', 'attendance', 'exams', 'exam_results',
    'assignments', 'notes', 'recommendations', 'notifications',
    'device_tokens', 'audit_logs'
  ];
begin
  foreach t in array tables loop
    -- التأكد من تفعيل RLS
    execute format('alter table public.%I enable row level security;', t);
    
    -- حذف السياسة القديمة في حال إعادة التشغيل
    execute format('drop policy if exists "center_app_all_%s" on public.%I;', t, t);
    
    -- إنشاء السياسة الشاملة لتطبيق المركز
    execute format(
      'create policy "center_app_all_%s" on public.%I for all to anon, authenticated using (true) with check (true);',
      t, t
    );
  end loop;
end $$;
