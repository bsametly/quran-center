-- 1) إضافة الأعمدة الإضافية لجدول الملفات الشخصية (profiles) لتخزين اسم المستخدم وكلمة المرور
alter table public.profiles add column if not exists username text;
alter table public.profiles add column if not exists password text;
alter table public.profiles add column if not exists linked_id uuid;

-- 2) فك قيد الربط الإجباري بـ auth.users لجدول profiles
-- (يتيح تسجيل الطلاب والمحفظين بدون الحاجة لإنشاء إيميلات سحابية لكل طفل أو محفظ)
alter table public.profiles drop constraint if exists profiles_id_fkey;

-- 3) جعل profile_id في جدول teachers يقبل null وفك القيد الإجباري
alter table public.teachers alter column profile_id drop not null;
alter table public.teachers drop constraint if exists teachers_profile_id_fkey;

-- 4) ضبط ترقيم الطلاب ليكون تلقائياً عند عدم التمرير ويقبل التمرير المخصص
do $$
begin
  if exists (
    select 1 from information_schema.columns 
    where table_schema = 'public' and table_name = 'students' and column_name = 'student_number'
  ) then
    alter table public.students alter column student_number set generated by default;
  end if;
exception
  when others then
    null;
end $$;

